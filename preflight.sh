#!/bin/sh
# =============================================================================
# preflight.sh — 部署预检：nginx 语法 + Lua 运行时验证
#
# 用法：
#   ./preflight.sh
#
# 退出码：
#   0 — 全部通过
#   1 — nginx 语法错误
#   2 — Lua 运行时验证失败
# =============================================================================
set -e

PASS=0
APP_DIR="/app"

echo "═══════════════════════════════════════════════"
echo "  预检：$0"
echo "═══════════════════════════════════════════════"
echo ""

# --------------------------------------------------
# 1) nginx 语法检查
# --------------------------------------------------
echo "── [1/2] nginx 语法检查 ──"
if nginx -t 2>&1; then
    echo "  ✓ nginx 语法检查通过"
    echo ""
else
    echo "  ✗ nginx 语法错误"
    echo ""
    echo "检查 conf/nginx.conf 和 conf/sites-available/ 下的配置文件"
    exit 1
fi

# --------------------------------------------------
# 2) Lua 运行时验证
# --------------------------------------------------
echo "── [2/2] Lua 运行时验证 ──"
if resty -I "$APP_DIR" -e 'package.cpath = "/usr/lib/lua/5.1/?.so;" .. package.cpath' "$APP_DIR/validate.lua"; then
    echo ""
    echo "  ✓ Lua 验证通过"
else
    RC=$?
    echo ""
    echo "  ✗ Lua 验证失败"
    echo ""
    echo "检查 src/lua/ 下的 Lua 模块和相关数据文件"
    exit 2
fi

# --------------------------------------------------
# 全部通过
# --------------------------------------------------
echo "═══════════════════════════════════════════════"
echo "  全部通过，准备就绪"
echo "═══════════════════════════════════════════════"
exit 0
